#!/usr/bin/env node
// Keep the engine's data model and lossless adapter conversions in sync with protobuf.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const base = 'cosmos/cardano-probabilistic-light-client-';
const module = 'github.com/cardano-foundation/cardano-ibc-incubator/' + base + 'core/state';
const source = fs.readFileSync(base + 'v8/probabilistic.pb.go', 'utf8');
const structs = [...source.matchAll(/^type (\w+) struct \{\n([\s\S]*?)^}/gm)].map(([, name, body]) => ({
  name,
  fields: [...body.matchAll(/^\s*(\w+)\s+([\w.*\[\]]+)\s+(`[^`]+`)/gm)].map(([, name, type, tags]) => ({ name, type, tags })),
}));
const names = new Set(structs.map(s => s.name));
const banner = '// Code generated by scripts/ci/generate-light-client-models.mjs. DO NOT EDIT.\n\n';
const model = banner + 'package state\n\nimport "time"\n\n' + structs.map(s =>
  `type ${s.name} struct {\n` + s.fields.map(f => `${f.name} ${f.type} ${f.tags}\n`).join('') + '}\n',
).join('\n');
let conversions = banner + `package probabilistic\n\nimport ("bytes"\nstate "${module}")\n\n`;
for (const direction of ['to', 'from']) {
  const prefix = direction === 'to' ? '' : 'state.';
  const dest = direction === 'to' ? 'state.' : '';
  for (const s of structs) {
    conversions += `func ${direction}Core${s.name}(value *${prefix}${s.name}) *${dest}${s.name} {\nif value == nil { return nil }\nreturn &${dest}${s.name}{\n`;
    for (const f of s.fields) {
      let value = `value.${f.name}`;
      if (f.type.startsWith('[]*') && names.has(f.type.slice(3))) {
        value = `mapCoreSlice(${value}, ${direction}Core${f.type.slice(3)})`;
      } else if (f.type.startsWith('*') && names.has(f.type.slice(1))) {
        value = `${direction}Core${f.type.slice(1)}(${value})`;
      } else if (f.type === '[]byte') {
        value = `bytes.Clone(${value})`;
      } else if (f.type === '[]string') {
        value = `mapCoreSlice(${value}, func(s string) string { return s })`;
      } else if (!['uint64', 'uint32', 'int64', 'string', 'bool', 'time.Duration'].includes(f.type)) {
        throw new Error(`unsupported field ${s.name}.${f.name}: ${f.type}`);
      }
      conversions += `${f.name}: ${value},\n`;
    }
    conversions += '}\n}\n\n';
  }
}
conversions += `func mapCoreSlice[A, B any](values []A, convert func(A) B) []B {
if values == nil { return nil }
result := make([]B, len(values))
for i, value := range values { result[i] = convert(value) }
return result
}
`;
for (const [file, content] of [
  [base + 'core/state/model.gen.go', model],
  [base + 'v8/core_conversion.gen.go', conversions],
  [base + 'v10/core_conversion.gen.go', conversions],
]) {
  const formatted = execFileSync('gofmt', { input: content, encoding: 'utf8' });
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== formatted) {
      throw new Error(`${file} is stale. Run node scripts/ci/generate-light-client-models.mjs`);
    }
  } else {
    fs.writeFileSync(file, formatted);
  }
}
