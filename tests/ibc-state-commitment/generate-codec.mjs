import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = dirname(fileURLToPath(import.meta.url))
const root = resolve(directory, '../..')
const runtime = resolve(root, 'packages/cardano-ibc-tx-builder-runtime/dist')
const require = createRequire(resolve(runtime, 'ibcStateRoot.js'))
const Lucid = require('@lucid-evolution/lucid')
const { serialisePlutusData } = require(resolve(runtime, 'plutusSerialise.js'))
const { encodeConnectionEndValue, encodeChannelEndValue, encodeModuleRegistration } = require(resolve(runtime, 'ibcStateRoot.js'))
const { ICS23MerkleTree } = require(resolve(runtime, 'ics23MerkleTree.js'))
const proofs = JSON.parse(readFileSync(resolve(directory, 'proofs.json'), 'utf8'))
const clientBytes = proofs.vectors.find((v) => v.name === 'client').committed
const clientData = Lucid.Data.from(clientBytes)
const hex = (text) => Buffer.from(text).toString('hex')
const vectors = []
const tests = [
  '// Generated by tests/ibc-state-commitment/generate-codec.mjs.',
  'use ibc/implementation/commitment_codec as codec',
  'use ibc/client/ics_007_tendermint_client/client_state.{ClientState}',
  'use ibc/client/ics_007_tendermint_client/consensus_state.{ConsensusState}',
  'use ibc/client/ics_007_tendermint_client/height.{Height}',
  'use ibc/client/ics_007_tendermint_client/types/unchecked_rational.{UncheckedRational}',
  'use ibc/core/ics_023_vector_commitments/merkle.{MerkleRoot}',
  'use ibc/core/ics_023_vector_commitments/merkle_prefix.{MerklePrefix}',
  'use ibc/core/ics_003_connection_semantics/types/connection_end.{ConnectionEnd}',
  'use ibc/core/ics_003_connection_semantics/types/counterparty.{Counterparty}',
  'use ibc/core/ics_003_connection_semantics/types/version.{Version}',
  'use ibc/core/ics_003_connection_semantics/types/state as connection_state',
  'use ibc/core/ics_004/types/channel.{Channel}',
  'use ibc/core/ics_004/types/counterparty.{ChannelCounterparty} as channel_counterparty',
  'use ibc/core/ics_004/types/state as channel_state',
  'use ibc/core/ics_004/types/order as channel_order',
  'use ibc/auth.{AuthToken}',
  'use ibc/core/ics_025_handler_interface/host_state.{ModuleRegistration}',
  '',
]
function add(name, kind, version, committed, expression, expected = {}) {
  vectors.push({ name, kind, version, committed, ...expected })
  tests.push(`test ${name}() { ${expression} == #"${committed}" }`, '')
}
const client = (path) => `ClientState {
  chain_id: "cosmos-2", trust_level: UncheckedRational { numerator: 1, denominator: 3 },
  trusting_period: 1209600000000000, unbonding_period: 1814400000000000,
  max_clock_drift: 10000000000, frozen_height: Height { revision_number: 0, revision_height: 0 },
  latest_height: Height { revision_number: 2, revision_height: 100 },
  proof_specs: merkle.get_sdk_specs(), upgrade_path: ${path},
}`
add('client_upgrade_path', 'client', 1, clientBytes, `codec.encode_client_state(${client('["upgrade", "upgradedIBCState"]')})`)
const emptyPath = new Lucid.Constr(0, [...clientData.fields.slice(0, 8), []])
add('client_empty_path', 'client', 1, serialisePlutusData(Lucid.Data.to(emptyPath)), `codec.encode_client_state(${client('[]')})`)
const legacy = new Lucid.Constr(0, clientData.fields.slice(0, 8))
add('client_legacy8', 'client', 0, serialisePlutusData(Lucid.Data.to(legacy)), `codec.encode_legacy_client_state(${client('[]')})`)
const consensus = proofs.vectors.find((v) => v.name === 'consensus_revision_2').committed
add('consensus', 'consensus', 1, consensus, `codec.encode_consensus_state(ConsensusState {
  timestamp: 1700000000000000000, next_validators_hash: #"${'11'.repeat(32)}",
  root: MerkleRoot { hash: #"${'22'.repeat(32)}" },
})`)
const connection = {
  client_id: hex('07-tendermint-0'), versions: [{ identifier: hex('1'), features: [hex('ORDER_ORDERED'), hex('ORDER_UNORDERED')] }],
  state: 'Open', counterparty: { client_id: hex('07-tendermint-9'), connection_id: hex('connection-2'), prefix: { key_prefix: hex('ibc') } },
  delay_period: 0n,
}
const states = ['Uninitialized', 'Init', 'TryOpen', 'Open', 'Closed']
for (const [state, name] of states.slice(0, 4).entries()) {
  const committed = await encodeConnectionEndValue({ ...connection, state: name }, Lucid)
  add(`connection_${state}`, 'connection', 1, committed, `codec.encode_connection(ConnectionEnd {
    client_id: "07-tendermint-0", versions: [Version { identifier: "1", features: ["ORDER_ORDERED", "ORDER_UNORDERED"] }],
    state: connection_state.${name}, counterparty: Counterparty {
      client_id: "07-tendermint-9", connection_id: "connection-2", prefix: MerklePrefix { key_prefix: "ibc" },
    }, delay_period: 0,
  })`, { state })
}
const channel = {
  state: 'Open', ordering: 'Unordered', counterparty: { port_id: hex('transfer'), channel_id: hex('channel-2') },
  connection_hops: [hex('connection-0')], version: hex('ics20-1'),
}
for (const [state, name] of states.entries()) {
  for (const [ordering, order] of ['None', 'Unordered', 'Ordered'].entries()) {
    // Freeze the historical five-field value even when the runtime writes the
    // fresh deployment's six-field upgrade-capable channel.
    const current = Lucid.Data.from(await encodeChannelEndValue({ ...channel, state: name === 'Closed' ? 'Close' : name, ordering: order, upgrade_sequence: 0n }, Lucid))
    const committed = serialisePlutusData(Lucid.Data.to(new Lucid.Constr(0, current.fields.slice(0, 5))))
    add(`channel_${state}_${ordering}`, 'channel', 1, committed, `codec.encode_channel(Channel {
      state: channel_state.${name}, ordering: channel_order.${order},
      counterparty: ChannelCounterparty { port_id: "transfer", channel_id: "channel-2" },
      connection_hops: ["connection-0"], version: "ics20-1", upgrade_sequence: 0,
    })`, { state, ordering })
  }
}
for (const sequence of [0n, 23n, 24n, 255n, 256n, 65535n, 65536n, 4294967295n, 4294967296n, 18446744073709551615n]) {
  add(`sequence_${sequence}`, 'sequence', 1, serialisePlutusData(Lucid.Data.to(sequence)), `codec.encode_sequence(${sequence})`, { sequence: sequence.toString() })
}
for (const size of [0, 1, 32, 64, 65, 128]) {
  const bytes = 'ab'.repeat(size)
  add(`bytes_${size}`, 'bytes', 1, serialisePlutusData(Lucid.Data.to(bytes)), `codec.encode_bytes(#"${bytes}")`, { bytes })
}
const registration = {
  module_script_hash: '33'.repeat(28), port_token: { policy_id: '44'.repeat(28), name: hex('port') },
  module_token: { policy_id: '55'.repeat(28), name: hex('module') },
}
add('registration', 'registration', 1, await encodeModuleRegistration(registration, Lucid), `codec.encode_registration(ModuleRegistration {
  module_script_hash: #"${registration.module_script_hash}",
  port_token: AuthToken { policy_id: #"${registration.port_token.policy_id}", name: "port" },
  module_token: AuthToken { policy_id: #"${registration.module_token.policy_id}", name: "module" },
})`)
const generated = execFileSync(process.env.AIKEN_BIN ?? 'aiken', ['fmt', '--stdin'], { input: tests.join('\n'), encoding: 'utf8' })
const tree = new ICS23MerkleTree()
const members = [
  { key: 'clients/07-tendermint-0/clientState', committed: clientBytes },
  { key: 'clients/07-tendermint-1/clientState', committed: vectors.find((v) => v.name === 'client_legacy8').committed },
]
for (const member of members) tree.set(member.key, member.committed)
const mixedProofs = members.map((member) => {
  const proof = tree.generateProof(member.key)
  return { ...member, root: tree.getRoot(), proof: { proofs: [{ exist: {
    key: proof.key.toString('hex'), value: proof.value.toString('hex'),
    path: proof.path.map((op) => ({ hash: op.hash, prefix: op.prefix.toString('hex'), suffix: op.suffix.toString('hex') })),
  } }] } }
})
const outputs = [
  [resolve(directory, 'codec.json'), `${JSON.stringify({ fixtureVersion: 1, vectors, mixedProofs }, null, 2)}\n`],
  [resolve(root, 'cardano/onchain/lib/ibc/implementation/commitment_codec_vectors.test.ak'), generated],
]
const mode = process.argv[2] ?? '--check'
assert.ok(mode === '--write' || mode === '--check', 'Use --write or --check')
for (const [file, contents] of outputs) {
  if (mode === '--write') writeFileSync(file, contents)
  else assert.equal(readFileSync(file, 'utf8'), contents, `${file} differs from the frozen codec vectors`)
}
