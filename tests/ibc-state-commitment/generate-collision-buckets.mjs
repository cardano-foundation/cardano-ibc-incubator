import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = dirname(fileURLToPath(import.meta.url))
const root = resolve(directory, '../..')
const require = createRequire(resolve(root, 'packages/cardano-ibc-tx-builder-runtime/package.json'))
const { ICS23MerkleTree } = require('./dist/ics23MerkleTree.js')
const commitment = require('./dist/ibcStateCommitment.js')
const gatewayRequire = createRequire(resolve(root, 'cardano/gateway/package.json'))
const { MerkleProof } = gatewayRequire('@cardano-ibc/proto-types/build/ibc/core/commitment/v1/commitment')

const key = 'commitments/ports/transfer/channels/channel-0/sequences/42'
const realKeyHash = commitment.keyHash
const target = realKeyHash(key)
const peerKeys = ['synthetic-collision-peer-0', 'synthetic-collision-peer-1']
const peerHashes = [Buffer.concat([target.subarray(0, 8), Buffer.alloc(24)]), Buffer.concat([target.subarray(0, 8), Buffer.alloc(24, 255)])]
// Finding real SHA-256 64-bit collisions is deliberately outside this test.
// Only these peer key digests are substituted. The requested key, all value
// hashes and every root hash use ordinary SHA-256 in all three languages.
commitment.keyHash = (candidate) => {
  const peer = peerKeys.indexOf(candidate)
  return peer < 0 ? realKeyHash(candidate) : peerHashes[peer]
}
const tree = new ICS23MerkleTree()
tree.set('ports/transfer', 'd8799f01ff')
tree.set(peerKeys[0], 'aabb')
const protoProof = (proof) => ({ key: proof.key, value: proof.value, path: proof.path })
const jsonProof = (proof) => ({ key: proof.key.toString('hex'), value: proof.value.toString('hex'), path: proof.path.map((op) => ({ hash: op.hash, prefix: op.prefix.toString('hex'), suffix: op.suffix.toString('hex') })) })
const vectors = []
const updates = []
function capture(name) {
  const value = tree.get(key)
  const proof = value ? tree.generateProof(key) : tree.generateNonExistenceProof(key).left
  assert.equal(tree.verifyProof(proof), true)
  const entry = value ? { exist: protoProof(proof) } : { nonexist: { key: proof.key, left: protoProof(proof) } }
  vectors.push({ name, key, committed: value?.toString('hex') ?? '', root: tree.getRoot(), siblings: tree.getSiblings(key).map((bytes) => bytes.toString('hex')), protobuf: Buffer.from(MerkleProof.encode({ proofs: [entry] }).finish()).toString('hex'), proof: { proofs: [value ? { exist: jsonProof(proof) } : { nonexist: { key: proof.key.toString('hex'), left: jsonProof(proof), right: null } }] } })
}
function change(name, value) {
  const before = { name, key, oldValue: tree.get(key)?.toString('hex') ?? '', newValue: value, oldRoot: tree.getRoot(), siblings: tree.getSiblings(key).map((bytes) => bytes.toString('hex')) }
  tree.set(key, value)
  updates.push({ ...before, newRoot: tree.getRoot() })
  capture(name)
}
capture('missing_in_singleton')
change('insert_collision', '010203')
change('update_collision', '040506')
tree.set(peerKeys[1], 'ccdd')
capture('three_entries')
change('delete_from_three', '')
change('reinsert_into_three', '070809')
tree.delete(peerKeys[1])
change('delete_to_singleton', '')
change('insert_after_collapse', '101112')
tree.delete(peerKeys[0])
capture('singleton_compatibility')
change('ordinary_delete', '')
commitment.keyHash = realKeyHash

const fixture = { version: 1, syntheticPeerDigests: peerHashes.map((digest) => digest.toString('hex')), vectors, updates }
const aiken = ['// Generated by tests/ibc-state-commitment/generate-collision-buckets.mjs.', '// Peer digests are synthetic. The requested key and all hashing are native.', 'use aiken/builtin', 'use ibc/core/ics_025_handler_interface/ibc_state_commitment as commitment', '']
const ordinaryPath = vectors[0].siblings.slice(1)
for (const entry of [...vectors, ...updates]) {
  assert.deepEqual(entry.siblings.slice(entry.siblings.length === 65 ? 1 : 0), ordinaryPath)
}
aiken.push('fn path_siblings() {', '  [', ...ordinaryPath.map((sibling) => `    #"${sibling}",`), '  ]', '}', '')
const witnessLines = (siblings) => siblings.length === 65
  ? ['  let witness =', '    [', `      #"${siblings[0]}",`, '      ..path_siblings()', '    ]']
  : ['  let witness = path_siblings()']
for (const vector of vectors) {
  aiken.push(`test collision_${vector.name}_proof() {`, ...witnessLines(vector.siblings), `  let key = "${key}"`, `  let value = #"${vector.committed}"`, '  let leaf =', '    commitment.leaf_hash(builtin.sha2_256(key), commitment.value_hash(value))', `  commitment.compute_root(key, leaf, witness) == #"${vector.root}"`, '}', '')
}
for (const update of updates) {
  aiken.push(`test collision_${update.name}_update() {`, ...witnessLines(update.siblings), '  commitment.apply_update(', `    #"${update.oldRoot}",`, `    "${key}",`, `    #"${update.oldValue}",`, `    #"${update.newValue}",`, '    witness,', `  ) == #"${update.newRoot}"`, '}', '')
}
// Exercise the validator with malformed descriptors against the same accepted
// old root. None may be used to erase a peer or to claim absence of this key.
const populated = vectors.find((vector) => vector.name === 'insert_collision')
const descriptor = Buffer.from(populated.siblings[0], 'hex')
const malformed = {
  wrong_marker: Buffer.concat([Buffer.from([3]), descriptor.subarray(1)]),
  truncated_record: descriptor.subarray(0, 128),
  duplicate_key: Buffer.concat([descriptor.subarray(0, 65), descriptor.subarray(1, 65)]),
  unsorted_keys: Buffer.concat([Buffer.from([2]), descriptor.subarray(65), descriptor.subarray(1, 65)]),
  missing_requested_key: descriptor.subarray(0, 65),
  wrong_path: Buffer.from(descriptor),
  empty_peer_value: Buffer.from(descriptor),
  changed_peer_value: Buffer.from(descriptor),
}
malformed.wrong_path[1] ^= 1
commitment.hash(Buffer.alloc(0)).copy(malformed.empty_peer_value, 33)
malformed.changed_peer_value[33] ^= 1
for (const [name, bytes] of Object.entries(malformed)) {
  aiken.push(`test collision_rejects_${name}() fail {`, ...witnessLines([bytes.toString('hex'), ...populated.siblings.slice(1)]), '  expect _ =', '    commitment.apply_update(', `      #"${populated.root}",`, `      "${key}",`, `      #"${populated.committed}",`, '      #"aabbcc",', '      witness,', '    )', '}', '')
}
aiken.push('test collision_rejects_false_absence() fail {', ...witnessLines(populated.siblings), '  expect _ =', '    commitment.apply_update(', `      #"${populated.root}",`, `      "${key}",`, '      #"",', '      #"aabbcc",', '      witness,', '    )', '}', '')

const mode = process.argv[2] ?? '--check'
assert.ok(mode === '--write' || mode === '--check', 'Use --write or --check')
for (const [path, content] of [
  [resolve(directory, 'collision-buckets.json'), `${JSON.stringify(fixture, null, 2)}\n`],
  [resolve(root, 'cardano/onchain/lib/ibc/core/ics-025-handler-interface/ibc_state_collision_vectors.test.ak'), aiken.join('\n')],
]) {
  if (mode === '--write') writeFileSync(path, content)
  else assert.equal(readFileSync(path, 'utf8'), content, `${path} differs from the shared tree output. Regenerate with --write.`)
}
